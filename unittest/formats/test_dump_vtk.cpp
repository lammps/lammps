TEST_F(DumpVTKTest, legacy_run0)
{
    const std::string dump_file = "dump_vtk_run0.vtk";
    const std::string box_file  = "dump_vtk_run0_boundingBox.vtk";
    generate_dump(dump_file, "id type", "sort id", 0);

    ASSERT_FILE_EXISTS(dump_file);
    auto lines = read_lines(dump_file);
    ASSERT_GT(lines.size(), 5);
    ASSERT_THAT(lines[0], Eq("# vtk DataFile Version 5.1"));
    ASSERT_THAT(lines[1], Eq("Generated by LAMMPS"));
    ASSERT_THAT(lines[2], Eq("ASCII"));
    ASSERT_THAT(lines[3], Eq("DATASET POLYDATA"));
    ASSERT_THAT(lines[4], Eq("POINTS 32 float"));

    auto text = slurp(dump_file);

    // one vertex cell per atom, so there is one offset more than atoms

    EXPECT_THAT(text, HasSubstr("VERTICES 33 32\n"));

    // the attributes become field data in the order of the dump command

    EXPECT_THAT(text, HasSubstr("POINT_DATA 32\nFIELD FieldData 2\n"));
    EXPECT_THAT(text, HasSubstr("id 1 32 int\n1 2 3 4 5 6 7 8 9\n"));
    EXPECT_THAT(text, HasSubstr("type 1 32 int\n1 1 1 1 1 1 1 1 1\n"));

    // the box dimensions go into a second file

    ASSERT_FILE_EXISTS(box_file);
    auto box = slurp(box_file);
    EXPECT_THAT(box, HasSubstr("DATASET RECTILINEAR_GRID\nDIMENSIONS 2 2 2\n"));
    EXPECT_THAT(box, HasSubstr("X_COORDINATES 2 float\n0 3.359"));
    EXPECT_THAT(box, HasSubstr("Y_COORDINATES 2 float\n0 3.359"));
    EXPECT_THAT(box, HasSubstr("Z_COORDINATES 2 float\n0 3.359"));

    delete_file(dump_file);
    delete_file(box_file);
}

