TEST_F(DumpVTKTest, single_precision_warning)
{
    const std::string dump_file = "dump_vtk_precision.vtk";
    const std::string box_file  = "dump_vtk_precision_boundingBox.vtk";

    // coordinates are stored in single precision, which is fine for the melt
    // system but not for an atom 20000 length units away from the origin

    auto output = CAPTURE_OUTPUT([&] {
        command(fmt::format("write_dump all vtk {} id type", dump_file));
    });
    EXPECT_THAT(output, Not(HasSubstr("single precision")));

    BEGIN_HIDE_OUTPUT();
    command("set atom 1 x 20000.0");
    END_HIDE_OUTPUT();

    output = CAPTURE_OUTPUT([&] {
        command(fmt::format("write_dump all vtk {} id type", dump_file));
    });
    EXPECT_THAT(output, HasSubstr("Dump vtk writes atom coordinates in single precision"));

    // with double precision output there is nothing to warn about

    output = CAPTURE_OUTPUT([&] {
        command(fmt::format("write_dump all vtk {} id type modify double yes", dump_file));
    });
    EXPECT_THAT(output, Not(HasSubstr("single precision")));
    EXPECT_THAT(slurp(dump_file), HasSubstr("POINTS 32 double\n"));

    delete_file(dump_file);
    delete_file(box_file);
}

