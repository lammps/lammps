// read a whole file, including the null bytes of binary data

static std::string slurp(const std::string &filename)
{
    std::ifstream in(filename, std::ios::binary);
    std::ostringstream buf;
    buf << in.rdbuf();
    return buf.str();
}

// pull the numbers between the first ">" after "marker" and the following "<"

static std::vector<double> xml_payload(const std::string &text, const std::string &marker)
{
    auto pos = text.find(marker);
    if (pos == std::string::npos) return {};
    pos = text.find('>', pos);
    if (pos == std::string::npos) return {};
    const auto end = text.find('<', pos);

    std::istringstream in(text.substr(pos + 1, end - pos - 1));
    std::vector<double> values;
    double v;
    while (in >> v)
        values.push_back(v);
    return values;
}

// legacy binary files store their data in big endian byte order

template <typename T> static T read_be(const char *p)
{
    const int one = 1;
    char buf[sizeof(T)];
    if (*((const char *)&one) == 1) {
        for (std::size_t i = 0; i < sizeof(T); ++i)
            buf[i] = p[sizeof(T) - 1 - i];
    } else {
        memcpy(buf, p, sizeof(T));
    }
    T v;
    memcpy(&v, buf, sizeof(T));
    return v;
}

class DumpVTKTest : public MeltTest {
public:
    void enable_triclinic()
    {
        BEGIN_HIDE_OUTPUT();
        command("change_box all triclinic");
        END_HIDE_OUTPUT();
    }

    void generate_dump(const std::string &dump_file, const std::string &fields,
                       const std::string &dump_modify_options, int ntimesteps)
    {
        BEGIN_HIDE_OUTPUT();
        command(fmt::format("dump id all vtk 1 {} {}", dump_file, fields));

        if (!dump_modify_options.empty()) {
            command(fmt::format("dump_modify id {}", dump_modify_options));
        }

        command(fmt::format("run {} post no", ntimesteps));
        END_HIDE_OUTPUT();
    }
};

