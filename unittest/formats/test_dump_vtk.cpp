TEST_F(DumpVTKTest, legacy_binary_run0)
{
    const std::string dump_file = "dump_vtk_binary.vtk";
    const std::string box_file  = "dump_vtk_binary_boundingBox.vtk";
    generate_dump(dump_file, "id type", "binary yes label \"my title\" sort id", 0);

    ASSERT_FILE_EXISTS(dump_file);
    auto data = slurp(dump_file);
    EXPECT_THAT(data, HasSubstr("# vtk DataFile Version 5.1\nmy title\nBINARY\n"));
    EXPECT_THAT(data, Not(HasSubstr("\nASCII\n")));

    // coordinates are stored as big endian floats.  the first atom sits in
    // the lower left corner of the box.

    const std::string points = "POINTS 32 float\n";
    auto pos                 = data.find(points);
    ASSERT_NE(pos, std::string::npos);
    pos += points.size();
    for (int i = 0; i < 3; ++i)
        EXPECT_FLOAT_EQ(read_be<float>(data.data() + pos + 4 * i), 0.0);
    EXPECT_EQ(data.compare(pos + 32 * 3 * 4, 10, "\nVERTICES "), 0);

    // integer attributes are stored as big endian 32-bit integers

    const std::string ids = "id 1 32 int\n";
    pos                   = data.find(ids);
    ASSERT_NE(pos, std::string::npos);
    pos += ids.size();
    for (int i = 0; i < 32; ++i)
        EXPECT_EQ(read_be<std::int32_t>(data.data() + pos + 4 * i), i + 1);

    // the box file is written in binary as well and gets the same title

    ASSERT_FILE_EXISTS(box_file);
    EXPECT_THAT(slurp(box_file), HasSubstr("my title\nBINARY\nDATASET RECTILINEAR_GRID\n"));

    delete_file(dump_file);
    delete_file(box_file);
}

